// Command genarchs writes supported_archs.txt: the architecture names of the pinned llama.cpp build,
// taken from LLM_ARCH_NAMES in src/llama-arch.cpp at the tag engine.lock names (PLAN §12.1). The agent
// reports the list in hello and the hub compares a model's general.architecture with it.
//
//	go run ./tools/genarchs                 fetches the source at the pinned tag from GitHub
//	go run ./tools/genarchs -src <file>     reads a local copy of llama-arch.cpp
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
)

var reArch = regexp.MustCompile(`\{\s*LLM_ARCH_([A-Z0-9_]+)\s*,\s*"([^"]+)"\s*\}`)

// skip are table rows that are not loadable text models.
var skip = map[string]bool{"UNKNOWN": true, "CLIP": true}

func main() {
	src := flag.String("src", "", "a local llama-arch.cpp (default: fetch at the pinned tag)")
	lock := flag.String("lock", "engine.lock", "engine.lock to read the tag from")
	out := flag.String("out", "supported_archs.txt", "file to write")
	flag.Parse()

	var pin struct {
		Tag string `json:"llama_tag"`
	}
	b, err := os.ReadFile(*lock)
	if err == nil {
		err = json.Unmarshal(b, &pin)
	}
	if err != nil || pin.Tag == "" {
		fail("cannot read the tag from %s: %v", *lock, err)
	}
	var text []byte
	if *src != "" {
		if text, err = os.ReadFile(*src); err != nil {
			fail("%v", err)
		}
	} else {
		url := "https://raw.githubusercontent.com/ggml-org/llama.cpp/" + pin.Tag + "/src/llama-arch.cpp"
		c := &http.Client{Timeout: 60 * time.Second}
		resp, err := c.Get(url)
		if err != nil {
			fail("%v", err)
		}
		defer resp.Body.Close()
		if resp.StatusCode != 200 {
			fail("%s: HTTP %d", url, resp.StatusCode)
		}
		if text, err = io.ReadAll(io.LimitReader(resp.Body, 8<<20)); err != nil {
			fail("%v", err)
		}
	}
	// Only the LLM_ARCH_NAMES table: it ends at the first "};" after its opening line.
	s := string(text)
	i := strings.Index(s, "LLM_ARCH_NAMES = {")
	if i < 0 {
		fail("LLM_ARCH_NAMES not found: the source layout changed")
	}
	s = s[i:]
	if j := strings.Index(s, "};"); j > 0 {
		s = s[:j]
	}
	seen := map[string]bool{}
	var names []string
	for _, m := range reArch.FindAllStringSubmatch(s, -1) {
		if skip[m[1]] || seen[m[2]] {
			continue
		}
		seen[m[2]] = true
		names = append(names, m[2])
	}
	if len(names) < 20 {
		fail("only %d architectures found: the source layout changed", len(names))
	}
	sort.Strings(names)
	body := "# Architectures of llama.cpp " + pin.Tag + " (LLM_ARCH_NAMES). Generated by tools/genarchs; do not edit.\n" + strings.Join(names, "\n") + "\n"
	if err := os.WriteFile(*out, []byte(body), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("%s: %d architectures for %s\n", *out, len(names), pin.Tag)
}

func fail(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "genarchs: "+format+"\n", a...)
	os.Exit(1)
}
